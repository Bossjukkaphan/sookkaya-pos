/**
 * ดึงข้อมูลให้ครบทุกแถวจาก PostgREST ซึ่งคืนได้จำกัดต่อหนึ่งคำขอแล้ว **ตัดทิ้งเงียบ ๆ**
 *
 * PostgREST มีเพดานจำนวนแถวต่อคำขอ (ค่าตั้งต้นราว 1,000) พอเกินแล้วมันไม่แจ้ง error
 * ไม่มีคำเตือน ส่งกลับมาแค่เท่าที่เพดานอนุญาตแล้วจบ ผลลัพธ์ที่ขาดไปหน้าตาเหมือน
 * ผลลัพธ์ที่สมบูรณ์ทุกประการ และผิดไปทางต่ำเสมอ จึงดูสมเหตุสมผลตลอดจนไม่มีใครเอะใจ
 *
 * เคยกัดร้านนี้มาแล้วสองรอบในวันเดียว (2026-08-11): หน้ารายงานบวกยอดจากบิลดิบ
 * ช่วง 60 วัน (1,115 บิล) แล้วได้ยอดขาดไป 83,631 บาท และหน้ายอดขายดึงเครดิตลูกค้า
 * 1,094 คนมาแล้วได้ไม่ครบ ทำให้ราว 94 คนไม่มียอดเครดิตขึ้นให้พนักงานเห็น
 */

/** ขอทีละเท่านี้ — ต่ำกว่าเพดานตั้งต้นของ PostgREST พอสมควรเพื่อความปลอดภัย */
export const PAGE_SIZE = 500

export type RowPage<T> = {
  data: T[] | null
  error: { message: string } | null
  /** จำนวนแถวจริงทั้งหมดตามเงื่อนไข — ได้มาเมื่อสั่ง select ด้วย { count: "exact" } */
  count: number | null
}

/**
 * ดึงทีละหน้าจนหมด แล้วเทียบกับจำนวนจริงที่ฐานข้อมูลบอกมาในหน้าแรก
 * ถ้าได้ไม่ครบให้ throw — ยอมให้งานล้มดีกว่าส่งข้อมูลที่ขาดออกไปโดยไม่มีใครรู้
 *
 * เงื่อนไขจบคือ "ได้แถวน้อยกว่าที่ขอ" ไม่ได้ผูกกับเลข 1,000 เพราะเพดานฝั่งเซิร์ฟเวอร์
 * ปรับได้ในหน้าตั้งค่าและเรายืนยันค่าจริงไม่ได้ การนับเทียบจึงถูกเสมอไม่ว่าเพดานเป็นเท่าไหร่
 *
 * ผู้เรียกต้องสั่ง order ด้วยคอลัมน์ที่ไม่ซ้ำกัน (เช่นปิดท้ายด้วย id) เสมอ
 * ถ้าลำดับไม่คงที่ระหว่างหน้า บางแถวจะถูกดึงซ้ำและบางแถวจะหายไป
 *
 * ถ้าระหว่างดึงมีคนบันทึกข้อมูลใหม่ จำนวนที่ได้จะเกินค่าที่จดไว้ ซึ่งไม่ถือว่าผิด
 * จึงตรวจเฉพาะกรณีได้น้อยกว่า
 */
export async function fetchAllRows<T>(
  fetchPage: (offset: number, limit: number) => PromiseLike<RowPage<T>>
): Promise<T[]> {
  const all: T[] = []
  let expected: number | null = null

  for (let offset = 0; ; offset += PAGE_SIZE) {
    const { data, error, count } = await fetchPage(offset, PAGE_SIZE)
    if (error) throw new Error(error.message)
    if (expected === null) expected = count
    const rows = data ?? []
    all.push(...rows)
    if (rows.length < PAGE_SIZE) break
  }

  if (expected !== null && all.length < expected) {
    throw new Error(`ดึงข้อมูลได้ไม่ครบ (ได้ ${all.length} จาก ${expected} แถว)`)
  }
  return all
}
