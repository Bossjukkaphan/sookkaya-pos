import { describe, expect, it } from "vitest"

import { turnAwayHour, turnAwayHourHistogram } from "./turn-away"

describe("turnAwayHour — ชั่วโมงที่ลูกค้าอยากได้คิว", () => {
  // เวลาบันทึกมักช้ากว่าเหตุการณ์จริง (เคสจริง 16/8: บันทึก 21:43 แต่ลูกค้าต้องการ 17:30)
  // จึงอ่านเวลาจากหมายเหตุก่อนเสมอ แล้วค่อยถอยไปใช้เวลาบันทึก

  it("หมายเหตุรูปแบบระบบ (คิวไลน์ HH:MM น.) → ใช้เวลานั้น", () => {
    expect(
      turnAwayHour("คิวไลน์ หนึ่ง 13:30 น. (1 ที่) — คิวช่วงเวลานั้นเต็ม", "2026-08-02T05:57:14+00:00")
    ).toBe(13)
  })

  it("พนักงานพิมพ์เอง จุดคั่น (17.30) → อ่านออก", () => {
    expect(turnAwayHour("นวดเท้า2คน17.30 คิวเต็ม", "2026-08-16T14:43:33+00:00")).toBe(17)
  })

  it("เวลาติดตัวหนังสือ (ตอน16.00 / 20.30น.) → อ่านออก", () => {
    expect(
      turnAwayHour("ลูกค้านวดเท้า60ตอน16.00แต่คิวว่างได้17.00", "2026-08-18T08:30:19+00:00")
    ).toBe(16)
    expect(turnAwayHour("Walk-in 2ท่านเวลา 20.30น. คิวเต็ม", "2026-07-30T13:30:54+00:00")).toBe(20)
  })

  it("เลขที่ไม่ใช่เวลา (นวดเท้า60, 90 นาที) ต้องไม่ถูกตีความเป็นเวลา", () => {
    // 60.30 ชั่วโมง 60 ไม่มีจริง → ข้ามไปหาตัวถัดไป / ไม่มีก็ใช้เวลาบันทึก
    expect(turnAwayHour("นวดไทย 90 นาที คิวเต็ม", "2026-08-16T14:43:03+00:00")).toBe(21)
  })

  it("ไม่มีเวลาในหมายเหตุ → ใช้เวลาบันทึก (เวลาไทย)", () => {
    // 14:43 UTC = 21:43 ไทย
    expect(turnAwayHour("คิวเต็มรับคิวไม่ทัน", "2026-08-16T14:43:03+00:00")).toBe(21)
    expect(turnAwayHour(null, "2026-08-16T03:05:00+00:00")).toBe(10)
  })

  it("นาทีเกิน 59 ไม่ใช่เวลา (เช่น ราคา 15.99)", () => {
    expect(turnAwayHour("พลาดยอด 15.99 ไป", "2026-08-16T14:43:03+00:00")).toBe(21)
  })
})

describe("turnAwayHourHistogram", () => {
  it("นับต่อชั่วโมง เรียงตามชั่วโมง เฉพาะชั่วโมงที่มีข้อมูล", () => {
    const rows = [
      { note: "คิวไลน์ ก 13:30 น. (1 ที่) — เต็ม", created_at: "2026-08-02T05:57:14+00:00" },
      { note: "นวดเท้า2คน17.30 คิวเต็ม", created_at: "2026-08-16T14:43:33+00:00" },
      { note: "17.45 เต็ม", created_at: "2026-08-16T10:00:00+00:00" },
      { note: null, created_at: "2026-08-16T10:30:00+00:00" }, // 17:30 ไทย
    ]
    expect(turnAwayHourHistogram(rows)).toEqual([
      { hour: 13, count: 1 },
      { hour: 17, count: 3 },
    ])
  })

  it("ไม่มีข้อมูล → ว่าง", () => {
    expect(turnAwayHourHistogram([])).toEqual([])
  })
})
