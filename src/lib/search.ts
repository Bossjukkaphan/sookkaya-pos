/**
 * สร้างเงื่อนไข or() ของ PostgREST สำหรับค้นหลายคอลัมน์แบบ ilike
 *
 * ทำไมต้องมีไฟล์นี้: PostgREST แยกเงื่อนไขใน or=(...) ด้วยจุลภาคและคุมกลุ่มด้วยวงเล็บ
 * ถ้าเอาคำค้นของผู้ใช้ต่อสตริงเข้าไปดิบๆ แค่พิมพ์จุลภาคก็ทำให้ทั้ง query พังเป็น 400
 * แล้วหน้าเว็บจะโชว์ "ไม่พบข้อมูล" แทนที่จะบอกว่าพัง — ผู้ใช้อ่านผิดว่าไม่มีข้อมูลจริง
 * (ทดสอบกับเซิร์ฟเวอร์จริง 29/7/2569: name.ilike.%a,b% ได้ 400 · name.ilike."%a,b%" ได้ 200)
 *
 * ครอบค่าด้วยเครื่องหมายคำพูดคู่ ทำให้จุลภาค/วงเล็บกลายเป็นตัวอักษรธรรมดา
 * แล้ว escape เครื่องหมายคำพูดกับแบ็กสแลชในคำค้นเอง
 *
 * หมายเหตุ: % และ _ ยังทำหน้าที่เป็นไวลด์การ์ดของ LIKE ตามเดิม
 * (คนพิมพ์ "50%" จะได้ผลกว้างกว่าที่ตั้งใจ แต่ไม่พังและไม่ใช่ช่องโหว่)
 */
export function ilikeOr(columns: string[], term: string): string {
  const value = `"%${term.replace(/[\\"]/g, "\\$&")}%"`
  return columns.map((c) => `${c}.ilike.${value}`).join(",")
}
