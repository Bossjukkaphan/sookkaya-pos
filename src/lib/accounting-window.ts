/**
 * หน้าต่างเวลาที่ยังแก้รายจ่ายได้ — ที่เดียวที่ตัดสินว่าเดือนไหนปิดงบแล้ว
 *
 * ของเดิมล็อกทันทีที่ขึ้นเดือนใหม่ ซึ่งไม่ตรงกับวิธีทำงานจริงของร้าน:
 * รายจ่ายปลายเดือน (เงินเดือน ค่ามือหมองวดสุดท้าย ค่าน้ำค่าไฟ) กว่าจะได้ใบเสร็จครบ
 * ก็ข้ามเดือนไปแล้ว พนักงานจึงคีย์ไม่ได้และต้องมาขอให้เจ้าของร้านแก้ให้ทุกเดือน
 * (เจอจริง 3/8/2569 — พนักงานไล่คีย์รายจ่ายเดือน ก.ค. ที่ค้างอยู่แล้วระบบไม่ยอมให้ลง)
 *
 * กติกาใหม่: เดือนก่อนหน้ายังแก้ได้จนถึงวันที่ 3 ของเดือนถัดไป พ้นจากนั้นปิดถาวร
 * เช่น รายจ่ายเดือน ก.ค. คีย์ได้ถึง 3 ส.ค. · วันที่ 4 ส.ค. เป็นต้นไปแตะไม่ได้แล้ว
 *
 * ทำไมต้องมีวันปิด ไม่เปิดตลอด: งบที่ส่งออกไปแล้วต้องไม่ขยับทีหลัง
 * ไม่งั้นตัวเลขที่เคยรายงานกับตัวเลขในระบบจะไม่ตรงกันโดยไม่มีใครรู้
 *
 * ไฟล์นี้มีสองหน้าต่าง อย่าสลับกันใช้:
 *   canEditExpenseOn        — รายจ่าย · เดือนก่อนถึงวันที่ 3 ของเดือนถัดไป (ยอดเดือนขยับจริง)
 *   canEditPaymentMethodOn  — ช่องทางชำระของบิลขาย · เดือนก่อนตลอดเดือน ไม่มีวันตัด
 *                             (ย้ายแค่ป้ายช่องทาง ยอดรวมไม่ขยับ จึงผ่อนได้)
 *
 * ส่วนที่ไม่ได้ใช้ไฟล์นี้: การแก้/ลบบิลขายเรื่องอื่น (updateSale/deleteSale) จำกัดเฉพาะ
 * เดือนปัจจุบัน · ใบเติมเงินสมาชิกแก้ช่องทางย้อนหลังได้ไม่จำกัดเดือน (Boss ตัดสิน 14 ส.ค. 2026
 * — เติมเงินมีน้อยและมักเจอที่ผิดตอนกระทบยอดข้ามเดือน ถ้าล็อกจะแก้ไม่ได้เลย)
 */

/** จำนวนวันผ่อนผันหลังสิ้นเดือน — วันที่ 1 ถึงวันที่นี้ของเดือนถัดไปยังแก้เดือนก่อนได้ */
export const CLOSE_GRACE_DAYS = 3

/** "2026-07" จากวันที่รูปแบบ ISO */
function monthOf(isoDate: string): string {
  return isoDate.slice(0, 7)
}

/** จำนวนเดือนที่ห่างกัน (บวก = a ใหม่กว่า b) — คำนวณจากปีคูณ 12 เพื่อให้ข้ามปีถูก */
function monthsBetween(a: string, b: string): number {
  const [ay, am] = a.split("-").map(Number)
  const [by, bm] = b.split("-").map(Number)
  return (ay - by) * 12 + (am - bm)
}

/**
 * รายจ่ายวันที่ `expenseDate` ยังแก้/ลบ/เพิ่มได้ไหม ถ้าวันนี้คือ `today`
 * (ทั้งคู่เป็น ISO "YYYY-MM-DD" ตามเวลาไทย)
 */
export function canEditExpenseOn(expenseDate: string, today: string): boolean {
  const gap = monthsBetween(monthOf(today), monthOf(expenseDate))

  // เดือนเดียวกัน — แก้ได้ตลอด
  if (gap === 0) return true

  // เดือนก่อนหน้าพอดี — แก้ได้ถ้ายังไม่พ้นวันผ่อนผัน
  if (gap === 1) return Number(today.slice(8, 10)) <= CLOSE_GRACE_DAYS

  // เก่ากว่านั้นปิดถาวร · อนาคตห้ามบันทึก (กันคีย์ปีผิดแล้วไปโผล่งบเดือนหน้า)
  return false
}

/**
 * แก้ "ช่องทางชำระเงิน" ของบิลวันที่ `recordDate` ได้ไหม ถ้าวันนี้คือ `today`
 * (ทั้งคู่เป็น ISO "YYYY-MM-DD" ตามเวลาไทย)
 *
 * ผ่อนกว่ารายจ่าย: เดือนปัจจุบันและเดือนก่อนหน้าแก้ได้ตลอด **ไม่มีวันตัด**
 * เพราะการเปลี่ยนช่องทางไม่ทำให้ยอดรวมของเดือนขยับสักบาท มันย้ายแค่ป้ายว่าเงินก้อนเดิม
 * เข้ามาทางไหน งบที่ส่งออกไปแล้วจึงไม่เปลี่ยน ต่างจากรายจ่ายที่การแก้ทำให้ยอดเดือนขยับจริง
 *
 * ที่ยังปิดสองเดือนขึ้นไป เพราะพ้นจากนั้นไม่มีใครจำได้แล้วว่าลูกค้าจ่ายด้วยอะไร
 * การแก้จึงเป็นการเดา ไม่ใช่การแก้ให้ถูก
 */
export function canEditPaymentMethodOn(recordDate: string, today: string): boolean {
  const gap = monthsBetween(monthOf(today), monthOf(recordDate))
  // เดือนเดียวกัน (0) หรือเดือนก่อนหน้าพอดี (1) — ติดลบคืออนาคต ห้ามเสมอ
  return gap === 0 || gap === 1
}
