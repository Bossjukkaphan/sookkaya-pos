/** จำนวนวันผ่อนผันหลังสิ้นเดือน — วันที่ 1 ถึงวันที่นี้ของเดือนถัดไปยังแก้เดือนก่อนได้ */
export const CLOSE_GRACE_DAYS = 3

/** "2026-07" จากวันที่รูปแบบ ISO */
function monthOf(isoDate: string): string {
  return isoDate.slice(0, 7)
}

/** จำนวนเดือนที่ห่างกัน (บวก = a ใหม่กว่า b) — คำนวณจากปีคูณ 12 เพื่อให้ข้ามปีถูก */
function monthsBetween(a: string, b: string): number {
  const [ay, am] = a.split("-").map(Number)
  const [by, bm] = b.split("-").map(Number)
  return (ay - by) * 12 + (am - bm)
}

/**
 * รายจ่ายวันที่ `expenseDate` ยังแก้/ลบ/เพิ่มได้ไหม ถ้าวันนี้คือ `today`
 * (ทั้งคู่เป็น ISO "YYYY-MM-DD" ตามเวลาไทย)
 */
export function canEditExpenseOn(expenseDate: string, today: string): boolean {
  const gap = monthsBetween(monthOf(today), monthOf(expenseDate))

  // เดือนเดียวกัน — แก้ได้ตลอด
  if (gap === 0) return true

  // เดือนก่อนหน้าพอดี — แก้ได้ถ้ายังไม่พ้นวันผ่อนผัน
  if (gap === 1) return Number(today.slice(8, 10)) <= CLOSE_GRACE_DAYS

  // เก่ากว่านั้นปิดถาวร · อนาคตห้ามบันทึก (กันคีย์ปีผิดแล้วไปโผล่งบเดือนหน้า)
  return false
}
