/** แบ่งทีมงานเป็น "ประจำ" กับ "เรียกเป็นครั้งคราว" (พาร์ทไทม์)
 *
 *  ทำไมต้องแยก: หน้าเข้างานถือว่าทุกคนที่ยังทำงานอยู่ต้องมาทุกวัน คนที่ไม่เช็คอิน
 *  จึงขึ้นวงแหวนแดงและทำให้ตัวเลข "มา x/N" ดูเหมือนขาดคนทุกวัน ทั้งที่พาร์ทไทม์
 *  ไม่ได้ถูกเรียกวันนั้นตั้งแต่แรก — ตัวเลขที่เตือนผิดทุกวันคือตัวเลขที่ไม่มีใครดู */

export type RosterMember = { is_part_time?: boolean | null }

/** คงลำดับเดิมของแต่ละกลุ่มไว้ (หน้าเรียกมาแล้วตาม sort/ชื่อ)
 *  ค่าที่หายไปถือว่าเป็นพนักงานประจำ — ระเบียนเก่าก่อนมีคอลัมน์นี้ต้องไม่เปลี่ยนพฤติกรรม */
export function splitByCallIn<T extends RosterMember>(
  staff: T[]
): { regular: T[]; onCall: T[] } {
  const regular: T[] = []
  const onCall: T[] = []
  for (const s of staff) (s.is_part_time ? onCall : regular).push(s)
  return { regular, onCall }
}
